# Fixed diagnostic thresholds; the correction function itself defaults to disabled.
PARAMS=dict(side_fraction=.035,side_step=6.,min_run_fraction=.25,min_run_span=40.,min_foreground=.5,smooth_step=6.,min_smooth_area=.35,default_enabled=False)


# Fingerprint original inputs/results and earlier experiments to detect unintended changes.
def protected_hashes():
    paths=[]
    for directory in ['PILOT','results','visual_quality_review','experiments/preprocessing_v2','experiments/row_background_tuning']:
        # Exclude Python-generated bytecode caches, which are unrelated to numerical results.
        paths.extend(p for p in (ROOT/directory).rglob('*') if p.is_file() and '__pycache__' not in p.parts)
    paths += [ROOT/'extract_features.py',ROOT/'test_features.py']
    return {str(p.relative_to(ROOT)):hashlib.sha256(p.read_bytes()).hexdigest() for p in paths}


# Check one vertical RGB side profile for a long, gradually changing color run.
def side_evidence(profile,params):
    # Subtract consecutive rows and measure each three-channel RGB step.
    jumps=np.linalg.norm(np.diff(profile,axis=0),axis=1)
    # Large jumps split the profile; np.r_ adds first/last endpoints for slicing each run.
    boundaries=np.r_[0,np.flatnonzero(jumps>params['side_step'])+1,len(profile)]
    runs=[]
    for start,end in zip(boundaries[:-1],boundaries[1:]):
        run=profile[start:end]
        # ptp is max minus min per channel; span distinguishes a gradient from a flat-color run.
        span=float(np.linalg.norm(np.ptp(run,axis=0)))
        runs.append(dict(start=int(start),end=int(end),length_fraction=float((end-start)/len(profile)),span=span))
    # A run must be long enough AND vary enough; a high coverage value alone is insufficient.
    qualifies=any(r['length_fraction']>=params['min_run_fraction'] and r['span']>=params['min_run_span'] for r in runs)
    return qualifies,runs


# Optionally subtract one smooth region; return the mask and the reason for acting/abstaining.
def correct_mask(rgb,baseline,enabled=False,params=PARAMS):
    # Copy the mask so the caller's baseline array is never changed in place.
    if not enabled:
        return baseline.copy(),dict(enabled=False,trigger=False,reason='baseline_default')
    # Read narrow side bands and use row medians to reduce the influence of isolated border pixels.
    h,w=baseline.shape; band=max(1,round(w*params['side_fraction']))
    left,left_runs=side_evidence(np.median(rgb[:,:band],axis=1),params)
    right,right_runs=side_evidence(np.median(rgb[:,-band:],axis=1),params)
    # Keep diagnostic evidence even when the correction abstains.
    info=dict(enabled=True,trigger=False,left_gradient=left,right_gradient=right,left_runs=left_runs,right_runs=right_runs,baseline_coverage=float(baseline.mean()),reason='insufficient_gradient_evidence')
    # All three conditions must hold before computing the removable smooth region.
    if not (left and right and baseline.mean()>params['min_foreground']):
        return baseline.copy(),info
    # Each pixel will receive its largest RGB difference from any side-sharing neighbor.
    values=rgb.astype(float); step=np.zeros((h,w))
    # Adjacent-column and adjacent-row differences are assigned to both participating pixels.
    horizontal=np.linalg.norm(np.diff(values,axis=1),axis=2)
    vertical=np.linalg.norm(np.diff(values,axis=0),axis=2)
    step[:,:-1]=np.maximum(step[:,:-1],horizontal); step[:,1:]=np.maximum(step[:,1:],horizontal)
    step[:-1]=np.maximum(step[:-1],vertical); step[1:]=np.maximum(step[1:],vertical)
    # Sharp object boundaries become barriers; smooth interiors may remain disconnected from background.
    smooth=(step<=params['smooth_step']).astype(np.uint8)
    # This helper uses four-connectivity only for smooth regions; final foreground features still use eight.
    _,labels,stats,_=cv2.connectedComponentsWithStats(smooth,connectivity=4)
    # Only regions touching BOTH side borders are candidates; label zero is not a smooth component.
    ids=set(labels[:,0]) & set(labels[:,-1]); ids.discard(0)
    # Require a large region to avoid acting on a few isolated border patches.
    eligible=[i for i in ids if stats[i,cv2.CC_STAT_AREA]/(h*w)>=params['min_smooth_area']]
    if not eligible:
        info['reason']='no_large_smooth_region_spanning_borders'
        return baseline.copy(),info
    # Choose the largest candidate, breaking ties by label to keep selection deterministic.
    chosen=max(eligible,key=lambda i:(stats[i,cv2.CC_STAT_AREA],-i))
    # Only remove foreground: no new foreground pixels or filled-interior reconstruction is introduced.
    result=baseline.copy(); result[labels==chosen]=0
    info.update(trigger=True,reason='suppress_one_smooth_border_connected_region',smooth_region_fraction=float(stats[chosen,cv2.CC_STAT_AREA]/(h*w)),removed_pixels=int(np.sum(baseline)-np.sum(result)))
    return result,info


# Render the same ROI beside both masks, box overlays and grid overlays.
def comparison(path,sid,rgb,baseline,candidate,old_mask,new_mask):
    # Display masks as black=0/background and white=255/foreground; overlays are copies.
    panels=[('Same original ROI',Image.fromarray(rgb)),('Original mask',Image.fromarray(old_mask*255).convert('RGB')),('Corrected mask',Image.fromarray(new_mask*255).convert('RGB')),('Original boxes',draw_boxes(rgb,baseline['boxes'])),('Corrected boxes',draw_boxes(rgb,candidate['boxes'])),('Original grid',layout_overlay(rgb,baseline['layout'])),('Corrected grid',layout_overlay(rgb,candidate['layout']))]
    canvas=Image.new('RGB',(1680,590),'white'); draw=ImageDraw.Draw(canvas); draw.text((5,5),sid,fill='black')
    for col,(title,panel) in enumerate(panels):
        draw.text((col*240+4,30),title,fill='black'); panel.thumbnail((232,512),Image.Resampling.LANCZOS); canvas.paste(panel,(col*240+(240-panel.width)//2,60))
    canvas.save(path)


# Run the fixed twelve-screen comparison and export evidence into a fresh directory.
def run(output):
    # Refusing an existing destination preserves previous experiment outputs.
    if output.exists(): raise ValueError('Use a fresh output directory')
    before=protected_hashes(); output.mkdir(parents=True)
    # Reuse the review selection; IDs select evaluation inputs, not correction behavior.
    selected=read_csv(ROOT/'visual_quality_review/selected_screens.csv')
    metadata={r['screen_id']:r for r in read_csv(ROOT/'PILOT/screenshots/screens.csv','utf-8-sig')}
    # Saved baseline outputs are read only and provide a reproduction reference.
    saved_palettes=json.loads((ROOT/'results/color_palettes.json').read_text()); saved_boxes=json.loads((ROOT/'results/bounding_boxes.json').read_text())
    saved_layouts={r['screen_id']:r for r in read_csv(ROOT/'results/layout_vectors.csv')}
    features={name:{} for name in ['baseline','candidate']}; differences=[]; triggers={}; mechanisms=[]
    (output/'comparisons').mkdir()
    sheets=[Image.new('RGB',(1000,1960),'white') for _ in range(3)]
    for index,row in enumerate(selected):
        sid=row['screen_id']; rgb,_=load_image(ROOT/'PILOT/screenshots'/metadata[sid]['image_path'],Config())
        # Use the full processed screenshot for both conditions; no cropping confounds the comparison.
        original,mask,edges=extract(rgb)
        # Check that the unmodified extractor reproduces the archived baseline features.
        assert original['palette']==saved_palettes[sid]['colors'] and original['boxes']==saved_boxes[sid]
        assert original['layout']==[float(saved_layouts[sid][f'cell_{i:02d}']) for i in range(32)]
        # Verify default preservation, then explicitly enable the one candidate for this experiment.
        disabled,_=correct_mask(rgb,mask)
        np.testing.assert_array_equal(disabled,mask)
        revised,info=correct_mask(rgb,mask,enabled=True)
        # Repeat the same correction to verify exact mask and diagnostic reproducibility.
        again,again_info=correct_mask(rgb,mask,enabled=True)
        np.testing.assert_array_equal(revised,again); assert info==again_info
        # This invariant prevents the correction from adding false foreground.
        assert np.all(revised<=mask)
        # Recompute only mask-dependent geometry/coverage; keep original palette and edge density.
        boxes,layout=geometry(revised,Config().min_component_area)
        candidate=dict(original,foreground_coverage=float(revised.mean()),boxes=boxes,layout=layout)
        validate(original); validate(candidate)
        features['baseline'][sid]=original; features['candidate'][sid]=candidate; triggers[sid]=info
        # Save inspection images without editing the dataset files.
        for name,array in [('roi',rgb),('baseline_mask',mask*255),('corrected_mask',revised*255)]:
            directory=output/name; directory.mkdir(exist_ok=True); Image.fromarray(array).save(directory/f'{sid}.png')
        # Record signed candidate-minus-baseline changes, including every grid cell.
        differences.append(dict(screen_id=sid,trigger=info['trigger'],baseline_foreground=original['foreground_coverage'],corrected_foreground=candidate['foreground_coverage'],foreground_delta=candidate['foreground_coverage']-original['foreground_coverage'],baseline_components=len(original['boxes']),corrected_components=len(boxes),component_delta=len(boxes)-len(original['boxes']),edge_delta=0.,palette_changed=False,changed_mask_pixels=int(np.count_nonzero(mask!=revised)),baseline_layout_mean=float(np.mean(original['layout'])),corrected_layout_mean=float(np.mean(layout)),**{f'cell_{i:02d}_delta':layout[i]-original['layout'][i] for i in range(32)}))
        comparison(output/'comparisons'/f'{sid}.png',sid,rgb,original,candidate,mask,revised)
        # Arrange four screenshots per contact sheet; index selects page and row position.
        sheet=sheets[index//4]; draw=ImageDraw.Draw(sheet); y=(index%4)*490; draw.text((5,y+5),sid+' | trigger='+str(info['trigger']),fill='black')
        for col,(name,image) in enumerate([('Original ROI',Image.fromarray(rgb)),('Original mask',Image.fromarray(mask*255).convert('RGB')),('Corrected mask',Image.fromarray(revised*255).convert('RGB')),('Corrected boxes',draw_boxes(rgb,boxes))]):
            draw.text((col*250+5,y+25),name,fill='black'); image.thumbnail((242,438),Image.Resampling.LANCZOS); sheet.paste(image,(col*250+(250-image.width)//2,y+48))
        mechanisms.append(dict(screen_id=sid,background_rgb=original['background_rgb'],original_foreground=original['foreground_coverage']))
        print(sid,info['trigger'],flush=True)
    # Export baseline and candidate numerical results separately with original screen IDs.
    for name,screens in features.items():
        directory=output/name; directory.mkdir()
        write_csv(directory/'visual_features.csv',[dict(screen_id=sid,foreground_coverage=f['foreground_coverage'],edge_density=f['edge_density'],component_count=len(f['boxes'])) for sid,f in screens.items()])
        write_csv(directory/'layout_vectors.csv',[dict(screen_id=sid,**{f'cell_{i:02d}':v for i,v in enumerate(f['layout'])}) for sid,f in screens.items()])
        write_json(directory/'bounding_boxes.json',{sid:f['boxes'] for sid,f in screens.items()}); write_json(directory/'color_palettes.json',{sid:f['palette'] for sid,f in screens.items()})
    for i,sheet in enumerate(sheets): sheet.save(output/f'contact_sheet_{i+1}.png')
    write_csv(output/'differences.csv',differences); write_json(output/'triggers.json',triggers); write_json(output/'background_diagnostics.json',mechanisms)
    # Record settings and ROI policy so the exact experiment can be reproduced.
    write_json(output/'configuration.json',dict(baseline=asdict(Config()),correction=PARAMS,experiment_enabled=True,ROI='Full original processed screenshot, identical to saved production baseline; no new cropping',sample_ids=[r['screen_id'] for r in selected]))
    # Verify protected bytes stayed unchanged during this run, then archive their fingerprints.
    assert before==protected_hashes(); write_json(output/'protected_sha256.json',before)
    write_json(output/'checks.json',dict(default_is_baseline=True,baseline_matches_saved=True,repeatability=True,no_new_foreground=True,protected_files_unchanged=True,decision='pending_visual_review'))


# Command-line entry point; importing this module only exposes its functions.
if __name__=='__main__':
    import argparse
    parser=argparse.ArgumentParser(description=__doc__); parser.add_argument('--output',type=Path,default=HERE/'run_01'); args=parser.parse_args(); output=args.output.resolve()
    # Restrict experiment writes to this directory tree.
    if not output.is_relative_to(HERE): parser.error('Output must be inside final experiment directory')
    run(output)
